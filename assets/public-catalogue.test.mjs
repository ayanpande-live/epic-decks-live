import assert from "node:assert/strict";
import {buildPublicCatalogue} from "./public-catalogue.mjs";
const now="2026-11-16T12:00:00Z";
const sample={public_id:"sample-1",unit_key:"mock-cert-001",title:"Example graded collectible",set_name:"Sample Set",grade_company:"PSA",grade_value:"10",language:"English",variant:"Holo",publication_approved:true,stock_status:"available",reserved:false,sold:false,cross_channel_check:true,availability_verified_at:"2026-11-16T11:00:00Z",media_rights:"seller_owned_photo",hero_image:"/images/demo.webp",approved_price_eur:"120.00",approved_marketplace_url:"https://www.ebay.nl/" , acquisition_cost_eur:"29.00", supplier_email:"private@example.com"};
const one=buildPublicCatalogue([sample],{asOf:now});
assert.equal(one.products.length,1);
assert.equal(one.products[0].action,"external_marketplace");
assert.equal(one.products[0].price_eur,"120.00");
assert.ok(!JSON.stringify(one.products).includes("29.00"));
assert.ok(!JSON.stringify(one.products).includes("private@example.com"));
assert.equal(buildPublicCatalogue([{...sample,stock_status:"sold"}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,reserved:true}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,cross_channel_check:false}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,availability_verified_at:"2026-11-10T12:00:00Z"}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,media_rights:"rights_pending"}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,hero_image:"javascript:alert(1)"}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,approved_marketplace_url:"javascript:alert(1)"}],{asOf:now}).products[0].action,"enquiry_only");
assert.equal(buildPublicCatalogue([{...sample,approved_price_eur:"0"}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([sample,{...sample,public_id:"sample-2"}],{asOf:now}).products.length,0);
assert.equal(buildPublicCatalogue([{...sample,publication_approved:false}],{asOf:now}).products.length,0);
assert.deepEqual(buildPublicCatalogue([],{asOf:now}).products,[]);
console.log("Public catalogue safety tests passed.");
